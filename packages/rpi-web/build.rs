use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn collect(root: &Path, directory: &Path, entries: &mut Vec<String>) {
    for entry in fs::read_dir(directory).expect("read frontend assets") {
        let entry = entry.expect("read frontend asset entry");
        let kind = entry.file_type().expect("read frontend asset type");
        assert!(
            !kind.is_symlink(),
            "frontend assets must not contain symlinks"
        );
        if kind.is_dir() {
            collect(root, &entry.path(), entries);
        } else if kind.is_file() {
            entries.push(
                entry
                    .path()
                    .strip_prefix(root)
                    .unwrap()
                    .to_str()
                    .unwrap()
                    .replace('\\', "/"),
            );
        }
    }
}

fn main() {
    let root = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("assets");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    println!("cargo:rerun-if-changed=assets");
    // `assets/` is generated by `npm run build` and is not tracked in git, so a
    // plain source checkout has no bundle. Compile with an empty inventory in
    // that case and let the server serve its "frontend not built" page;
    // release builds rebuild the frontend first so shipped crates embed it.
    if !root.join("index.html").is_file() {
        println!(
            "cargo:warning=rpi-web frontend bundle is missing; run `npm run build` in packages/rpi-web/frontend to embed the web UI"
        );
        fs::write(
            out_dir.join("frontend.rs"),
            "pub const FILES: &[(&str, &[u8])] = &[];\n",
        )
        .expect("write frontend inventory");
        return;
    }
    let mut entries = Vec::new();
    collect(&root, &root, &mut entries);
    entries.sort();
    let html = fs::read_to_string(root.join("index.html")).expect("read frontend index");
    for reference in html.split('"').filter_map(|s| s.strip_prefix("/assets/")) {
        assert!(
            entries
                .iter()
                .any(|name| name == &format!("assets/{reference}")),
            "missing frontend asset: {reference}"
        );
    }
    let mut source = "pub const FILES: &[(&str, &[u8])] = &[\n".to_string();
    for name in entries {
        source.push_str(&format!(
            "({name:?}, include_bytes!({:?})),\n",
            root.join(&name).to_str().unwrap()
        ));
    }
    source.push_str("];\n");
    fs::write(out_dir.join("frontend.rs"), source).unwrap();
}
